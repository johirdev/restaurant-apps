/**
 * এক ডাকে সর্বোচ্চ কতগুলো। সীমাটা ইচ্ছে করেই — পুরো টেবিল সিলেক্ট করে
 * "সব মুছে দাও" বললে সার্ভারলেস ফাংশন টাইমআউটের আগেই কাজ শেষ হওয়া চাই,
 * আর ভুল ক্লিকে হাজারটা সারি একসাথে উধাও হওয়ার সুযোগও থাকে না।
 */
export const BULK_DELETE_MAX = 100;

export const bulkDeleteSchema = z.object({
  ids: z
    .array(
      z
        .string()
        .trim()
        .refine((id) => mongoose.Types.ObjectId.isValid(id), "Invalid id"),
    )
    .min(1, "Select at least one row to delete")
    .max(BULK_DELETE_MAX, `You can delete at most ${BULK_DELETE_MAX} rows at a time`)
    // একই আইডি দুবার এলে দুবার মোছার চেষ্টা হতো, আর "কয়টা মুছল" এর
    // হিসাবটাও ভুল দেখাত — তাই ঢোকার মুখেই আলাদা করে নিই
    .transform((ids) => [...new Set(ids)]),
});

export type BulkDeleteInput = z.infer<typeof bulkDeleteSchema>;
