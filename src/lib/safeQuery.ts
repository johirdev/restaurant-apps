/** রেজেক্সের বিশেষ অক্ষরগুলোকে আক্ষরিক বানায় */
export const escapeRegex = (input: string): string =>
  input.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** সার্চ টার্ম — লম্বা ইনপুট ছেঁটে, বিশেষ অক্ষর নিরপেক্ষ করে */
export const sanitizeSearchTerm = (value: unknown, maxLength = 60): string => {
  if (typeof value !== "string") return "";
  return value.trim().slice(0, maxLength);
};

/**
 * "শুরুতে মিলুক" রেজেক্স — মঙ্গো এটাকে ইনডেক্স রেঞ্জ হিসেবে চালাতে পারে,
 * তাই এক বছরের ডেটাতেও সার্চ দ্রুত থাকে। মাঝখানে মেলানো (`/term/`)
 * সবসময় পুরো কালেকশন স্ক্যান করে, তাই সেটা এড়ানো হয়।
 */
export const prefixRegex = (term: string) =>
  new RegExp(`^${escapeRegex(term)}`, "i");

/** মাঝখানেও মিলুক — শুধু ছোট, ইনডেক্স-বিহীন কালেকশনে ব্যবহার করুন */
export const containsRegex = (term: string) =>
  new RegExp(escapeRegex(term), "i");

/**
 * `sortBy` কোয়েরি প্যারাম — শুধু চেনা ফিল্ডেই সাজানো যাবে।
 * অচেনা ফিল্ডে সাজালে মঙ্গো ইনডেক্স ছাড়াই মেমোরিতে সাজাতে যায়, আর
 * বড় কালেকশনে সেটা সরাসরি এরর (`Sort exceeded memory limit`) বা
 * ভয়ানক ধীরগতি হয়ে দাঁড়ায়।
 */
export const safeSortBy = (
  value: unknown,
  allowed: readonly string[],
  fallback = "createdAt",
): string => (typeof value === "string" && allowed.includes(value) ? value : fallback);
